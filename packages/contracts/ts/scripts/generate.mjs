// Generates TypeScript types from the contracts JSON Schema (ADR-0008).
// Usage: node scripts/generate.mjs           write src/generated/*
//        node scripts/generate.mjs --check   exit 1 if src/generated/* is stale
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { compile } from "json-schema-to-typescript";

const here = dirname(fileURLToPath(import.meta.url));
const schemaPath = resolve(here, "../../schemas/contracts.schema.json");
const outDir = resolve(here, "../src/generated");
const banner = [
  "/*",
  " * Generated by packages/contracts/ts/scripts/generate.mjs",
  " * from packages/contracts/schemas/contracts.schema.json. Do not edit.",
  " * Source of truth: packages/contracts/python. Regenerate: npm run contracts:gen",
  " */",
].join("\n");

const schema = JSON.parse(await readFile(schemaPath, "utf8"));
const versionValue = JSON.stringify(schema["x-contracts-version"]);

// A property like {"$ref": "#/$defs/UncertaintyType", "default": "none"} would become a
// duplicate type (UncertaintyType1). Defaults do not change TypeScript types, so keep the $ref only.
for (const definition of Object.values(schema.$defs)) {
  const properties = definition.properties ?? {};
  for (const [name, property] of Object.entries(properties)) {
    if ("$ref" in property) properties[name] = { $ref: property.$ref };
  }
}
const compiled = await compile(schema, "MultiverseContracts", {
  bannerComment: banner,
  unreachableDefinitions: true,
  additionalProperties: false,
  // An upper bound (tags: at most 10) stays a runtime rule; as a union of 11 tuple types it
  // would only make the TypeScript unusable.
  maxItems: -1,
  style: { printWidth: 100 },
});

// The root document only holds $defs and compiles to an empty catch-all interface. Drop it;
// fail loudly if the generator output changes shape so the drop is never silently wrong.
const rootInterface =
  /\/\*\*\n \* Generated from packages\/contracts\/python\. Do not edit by hand\.\n \*\/\nexport interface MultiverseContracts \{\n {2}\[k: string\]: unknown;\n\}\n/;
if (!rootInterface.test(compiled)) {
  throw new Error("Unexpected shape of the root interface in generated contracts.");
}
const types = compiled.replace(rootInterface, "").replaceAll(/\n\n\n+/g, "\n\n");
const version = `${banner}\n\nexport const CONTRACTS_VERSION = ${versionValue};\n`;
const outputs = { "contracts.ts": types, "version.ts": version };

if (process.argv.includes("--check")) {
  const stale = [];
  for (const [name, content] of Object.entries(outputs)) {
    const current = await readFile(resolve(outDir, name), "utf8").catch(() => "");
    if (current !== content) stale.push(name);
  }
  if (stale.length > 0) {
    console.error(`Stale generated files: ${stale.join(", ")}. Run: npm run contracts:gen`);
    process.exit(1);
  }
  console.log("Generated TypeScript contracts are up to date.");
} else {
  await mkdir(outDir, { recursive: true });
  for (const [name, content] of Object.entries(outputs)) {
    await writeFile(resolve(outDir, name), content, "utf8");
  }
  console.log(`Wrote ${Object.keys(outputs).length} files to ${outDir}`);
}
